"""Packs every .glb in game/assets into game/models.js so the game runs from a single
folder with no web server (file://, Capacitor, artifact links).
Each model's external texture is embedded inside the GLB first.
Usage: python3 tools/pack_models.py   (run from the game folder)"""
import base64, json, os, struct, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS = os.path.join(ROOT, 'assets')

def embed_textures(path):
    data = open(path, 'rb').read()
    jlen = struct.unpack('<I', data[12:16])[0]
    gltf = json.loads(data[20:20 + jlen])
    bin_start = 20 + jlen
    blen = struct.unpack('<I', data[bin_start:bin_start + 4])[0]
    binary = bytearray(data[bin_start + 8:bin_start + 8 + blen])
    for img in gltf.get('images', []):
        if 'uri' not in img:
            continue
        png = open(os.path.join(os.path.dirname(path), img.pop('uri')), 'rb').read()
        while len(binary) % 4:
            binary.append(0)
        gltf.setdefault('bufferViews', []).append({'buffer': 0, 'byteOffset': len(binary), 'byteLength': len(png)})
        img['bufferView'] = len(gltf['bufferViews']) - 1
        img['mimeType'] = 'image/png'
        binary += png
    while len(binary) % 4:
        binary.append(0)
    gltf['buffers'][0]['byteLength'] = len(binary)
    j = json.dumps(gltf, separators=(',', ':')).encode()
    j += b' ' * ((4 - len(j) % 4) % 4)
    total = 12 + 8 + len(j) + 8 + len(binary)
    return (struct.pack('<4sII', b'glTF', 2, total) + struct.pack('<I4s', len(j), b'JSON') + j
            + struct.pack('<I4s', len(binary), b'BIN\x00') + bytes(binary))

out = {}
for dirpath, _, files in os.walk(ASSETS):
    for f in sorted(files):
        if f.endswith('.glb'):
            full = os.path.join(dirpath, f)
            out[os.path.relpath(full, ASSETS).replace(os.sep, '/')] = base64.b64encode(embed_textures(full)).decode()

with open(os.path.join(ROOT, 'models.js'), 'w') as fh:
    fh.write('// Generated by tools/pack_models.py from assets/ (Kenney, CC0). Do not edit by hand.\n')
    fh.write('window.GAME_MODELS = ' + json.dumps(out, indent=0) + ';\n')
print(f'packed {len(out)} models -> models.js ({os.path.getsize(os.path.join(ROOT, "models.js")) // 1024} KB)')
